// Run before deploying: node tools/make-widget-data.mjs
// Reads the day's numbers from site/index.html and writes:
//   api/functions/widget-data.json  (fallback numbers for the home-screen widget)
//   site/config.js                  (tells the Daybook page where the API is and its key)
// Needs DAYBOOK_API_URL and DAYBOOK_KEY (or api/.daybook-key). Only deploy config.js to a site behind a login.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "site/index.html"), "utf8");
const grab = (name) => {
  const m = html.match(new RegExp("const " + name + "=([\\s\\S]*?);\\n(?:const|let|function)"));
  if (!m) throw new Error("Could not find " + name + " in index.html");
  return Function("return (" + m[1] + ")")();
};
const P = grab("P");
const DATA = grab("DATA");
const strip = (s) => String(s).replace(/<[^>]+>/g, "").replace(/&amp;/g, "&");

const data = {
  date: String(P.date).split(" · ")[0],
  kpis: P.kpis.map((k) => ({ n: k[0], label: strip(k[1]), tone: k[2] || "" })),
  roles: DATA.jobs.length,
  messages: DATA.msgs.length,
  next: P.dead.slice(0, 3).map((d) => ({ what: strip(d[0]), when: strip(d[1]) })),
  generated: new Date().toISOString(),
};
writeFileSync(join(root, "api/functions/widget-data.json"), JSON.stringify(data, null, 2));

const url = (process.env.DAYBOOK_API_URL || "").replace(/\/$/, "");
const key = process.env.DAYBOOK_KEY || readFileSync(join(root, "api/.daybook-key"), "utf8").trim();
if (!url) throw new Error("Set DAYBOOK_API_URL, e.g. https://<your-api-site>.netlify.app/api");
writeFileSync(
  join(root, "site/config.js"),
  "// Generated by tools/make-widget-data.mjs. Deploy only to a site behind a login.\nwindow.DAYBOOK_API={url:" + JSON.stringify(url) + ",key:" + JSON.stringify(key) + "};\n"
);
console.log("widget data:", data.date, data.kpis.length, "numbers,", data.next.length, "dates");
